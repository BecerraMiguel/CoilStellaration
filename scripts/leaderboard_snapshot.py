"""Snapshot of the CoilStellaration leaderboard as a Markdown report.

Reads the per-submission summaries the leaderboard Space publishes in the public dataset
`proxima-fusion/coilstellaration-bench-results` (only the small `*.json` files) and writes
`docs/reports/leaderboard_snapshots/<date>.md` with, per track:
  - the score ranking (strict feasibility, then mean; the "Score ranking" tab), all strata pooled,
    plus strict on the tight stratum, mean inference time and parameter count;
  - the first Pareto front of strict feasibility vs. mean inference time (what the Space's front
    page highlights since upstream c60811b).

Usage:
    uv run python scripts/leaderboard_snapshot.py            # today's date
    uv run python scripts/leaderboard_snapshot.py --date 2026-11-26
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import tempfile

from huggingface_hub import HfApi, snapshot_download

RESULTS_REPO = "proxima-fusion/coilstellaration-bench-results"
TRACKS = ("fixed_shape", "variable_shape")
OUT_DIR = pathlib.Path(__file__).resolve().parents[1] / "docs" / "reports" / "leaderboard_snapshots"


def load_records(revision: str) -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        root = snapshot_download(
            RESULTS_REPO,
            repo_type="dataset",
            revision=revision,
            allow_patterns=["*.json"],
            local_dir=tmp,
        )
        records = []
        for path in pathlib.Path(root).rglob("*.json"):
            if ".cache" in path.parts:
                continue
            record = json.loads(path.read_text())
            if isinstance(record, dict) and record.get("status") == "FINISHED":
                records.append(record)
    return records


def rows_for_track(records: list[dict], track: str) -> list[dict]:
    rows = []
    for r in records:
        t = r.get("tracks", {}).get(track)
        if not t:
            continue
        tight = t.get("strata", {}).get("tight", {})
        time_s = (t.get("inference_time") or {}).get("mean")
        rows.append(
            {
                "model": r["model"],
                "commit": (r.get("commit_hash") or "")[:7],
                "date": (r.get("submitted_time") or "")[:10],
                "strict": t.get("strict_feasibility", float("nan")),
                "mean": t.get("mean", float("nan")),
                "tight_strict": tight.get("strict_feasibility", float("nan")),
                "time_s": time_s,
                "params": r.get("n_parameters"),
                "n": t.get("n"),
            }
        )
    rows.sort(key=lambda x: (-x["strict"], -x["mean"]))
    return rows


def pareto_front(rows: list[dict]) -> list[dict]:
    """Rows no other row beats on both strict (higher) and time (lower)."""
    timed = [r for r in rows if r["time_s"] is not None]
    front = [
        r
        for r in timed
        if not any(
            o["strict"] >= r["strict"]
            and o["time_s"] <= r["time_s"]
            and (o["strict"] > r["strict"] or o["time_s"] < r["time_s"])
            for o in timed
        )
    ]
    return sorted(front, key=lambda x: x["time_s"])


def fmt_time(s: float | None) -> str:
    return "—" if s is None else f"{s * 1000:,.0f}"


def fmt_params(p: int | None) -> str:
    return "—" if not p else f"{p / 1e6:.2f} M"


def table(rows: list[dict]) -> list[str]:
    lines = [
        "| # | model | commit | date | strict | mean | strict (tight) | time (ms) | params |",
        "|---:|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for i, r in enumerate(rows, 1):
        lines.append(
            f"| {i} | `{r['model']}` | {r['commit']} | {r['date']} | {r['strict']:.3f} | "
            f"{r['mean']:.3f} | {r['tight_strict']:.3f} | {fmt_time(r['time_s'])} | "
            f"{fmt_params(r['params'])} |"
        )
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--date", default=dt.date.today().isoformat())
    args = parser.parse_args()

    info = HfApi().dataset_info(RESULTS_REPO)
    records = load_records(info.sha)

    out = [
        f"# Leaderboard snapshot — {args.date}",
        "",
        f"Source: `{RESULTS_REPO}` at revision `{info.sha}` (last modified "
        f"{info.last_modified:%Y-%m-%d %H:%M} UTC), {len(records)} finished submissions. "
        "Generated by `scripts/leaderboard_snapshot.py`.",
        "",
        "All strata pooled unless noted. `strict` = strict feasibility; `mean` = mean instance "
        "score S; `time` = mean inference time per instance on the evaluator. Each row is one "
        "submitted revision, so a model can appear several times. Rows are not labelled pure "
        "vs. hybrid: the results do not record it.",
    ]
    for track in TRACKS:
        rows = rows_for_track(records, track)
        out += ["", f"## `{track}` ({len(rows)} submissions, n = {rows[0]['n'] if rows else 0})"]
        out += ["", "### Pareto front 1: strict vs. inference time", ""]
        out += table(pareto_front(rows))
        out += ["", "### Score ranking (strict, then mean)", ""]
        out += table(rows)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{args.date}.md"
    path.write_text("\n".join(out) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
